local H = dofile("tests/helpers.lua")
local Tools = require("plugin_tools")
local U = require("plugin_tools.util")
local source = H.repo("health")
local m = Tools.new({
  root = H.root .. "/packages",
  lockfile = H.root .. "/lock.json",
  specs = { { id = "health", source = source } },
})
H.wait(m:install())
local function messages()
  return vim.inspect(m:diagnostics())
end
H.case("healthy packages have no issues and explicit inspection detects drift", function()
  H.eq(m:diagnostics(), {})
  H.write(m.graph.packages.health.dir .. "/local-file", "local")
  assert(messages():find("local checkout modifications", 1, true))
  vim.fn.delete(m.graph.packages.health.dir .. "/local-file")
  H.write(source .. "/next", "next")
  H.commit(source, "new commit")
  H.wait(m:update())
  local lock = U.read_json(m.lockfile)
  lock.plugins.health.commit = string.rep("a", 40)
  U.write_json(m.lockfile, lock)
  assert(messages():find("differs from locked revision", 1, true))
  H.wait(m:freeze())
  H.eq(m:diagnostics(), {})
end)
H.case("interrupted locks and malformed journals have recovery advice", function()
  local dir = m.graph.root .. "/.operation-lock"
  vim.fn.mkdir(dir, "p")
  U.write_json(dir .. "/owner.json", { pid = vim.uv.os_getpid(), finished = true })
  assert(messages():find("Interrupted or incomplete", 1, true))
  assert(messages():find("no transaction journal", 1, true))
  U.write_json(dir .. "/journal.json", { version = 1, root = "/wrong", lockfile = m.lockfile })
  assert(messages():find("does not match", 1, true))
  U.write_json(dir .. "/owner.json", { pid = vim.uv.os_getpid() })
  assert(messages():find("held by a running process", 1, true))
  assert(not messages():find("differs from locked revision", 1, true))
  vim.fn.delete(dir, "rf")
end)
H.case("malformed locks and previous failures are inspectable without throwing", function()
  H.write(m.lockfile, "broken")
  assert(messages():find("invalid JSON", 1, true))
  H.wait(m:install(), "invalid JSON")
  assert(messages():find("Last install operation failed", 1, true))
  vim.fn.delete(m.lockfile)
  m.last_operation = nil
  assert(messages():find("no locked revision", 1, true))
end)
H.finish()
